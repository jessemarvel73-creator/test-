async def get_promo_usage_counts(conn, promo_id, user_id=None):
    """Return authoritative successful promo-use counts.

    Usage is measured in eligible inventory units. Each successful checkout
    creates one promo_redemptions row with the exact quantity discounted by the
    promo. promo_codes.used_count remains a compatibility cache only.
    """
    promo_id = int(promo_id)
    total_used = int(await conn.fetchval(
        "SELECT COALESCE(SUM(quantity), 0) FROM promo_redemptions WHERE promo_code_id=$1",
        promo_id,
    ) or 0)
