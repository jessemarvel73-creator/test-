async def validate_pending_order(
    order_id,
    telegram_id,
    total_stars,
    currency,
):
    """Validate every line of a pending Stars order before Telegram confirms payment."""
    if currency != "XTR":
        return False

    pool = await get_pool()
    async with pool.acquire() as conn:
        order = await conn.fetchrow(
            """
            SELECT o.id, o.user_id, o.status, o.total_stars, u.telegram_id
            FROM orders o
            JOIN users u ON u.id=o.user_id
            WHERE o.id=$1 AND u.telegram_id=$2
            FOR UPDATE
            """,
            int(order_id), int(telegram_id),
        )
        if not order or order["status"] != "pending":
            return False
        if int(order["total_stars"] or 0) != int(total_stars):
            return False

        items = await conn.fetch(
            """
            SELECT oi.product_id, oi.quantity, p.stock, p.active
            FROM order_items oi
            LEFT JOIN products p ON p.id=oi.product_id
            WHERE oi.order_id=$1
            ORDER BY oi.id ASC
            """,
            int(order_id),
        )
        if not items:
            return False

        for item in items:
            quantity = int(item["quantity"] or 0)
            if quantity <= 0 or not item["product_id"]:
                return False
            if not item["active"]:
                return False
            if int(item["stock"] or 0) < quantity:
                return False

            available_count = await conn.fetchval(
                "SELECT COUNT(*) FROM inventory_items WHERE product_id=$1 AND status='available'",
                int(item["product_id"]),
            )
            if int(available_count or 0) < quantity:
                return False

    return True


