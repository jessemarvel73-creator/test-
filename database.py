async def _require_available_inventory(conn, product_id, quantity):
    """Require enough available inventory for a sale attempt."""
    quantity = int(quantity)
    if quantity <= 0:
        raise ValueError("Invalid quantity.")
    available = await conn.fetchval(
        "SELECT COUNT(*) FROM inventory_items WHERE product_id=$1 AND status='available'",
        int(product_id),
    )
    available = int(available or 0)
    if available < quantity:
        raise ValueError("Product is not ready for sale. Add inventory first.")
    return available


