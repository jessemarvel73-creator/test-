async def get_referral_discount(telegram_id, conn=None):
    """Return the currently earned referral discount percentage for a user.

    Each successful referral grants REFERRAL_DISCOUNT_PER_USER percent for
    REFERRAL_DISCOUNT_DAYS days, capped at REFERRAL_MAX_DISCOUNT.
    """
    import config
    referral_settings = await get_referral_settings()
    days = referral_settings["days"]
    per_user = referral_settings["per_user"]
    maximum = referral_settings["max_discount"]
    if per_user <= 0 or maximum <= 0:
        return {"discount_percent": 0, "referral_count": 0}

    own_conn = False
    if conn is None:
        pool = await get_pool()
        conn = await pool.acquire()
        own_conn = True
    try:
        if days <= 0:
            row = await conn.fetchrow(
                """
                SELECT COUNT(*)::INT AS referral_count
                FROM referrals
                WHERE referrer_user_id = (SELECT id FROM users WHERE telegram_id = $1)
                """,
                int(telegram_id),
            )
        else:
            row = await conn.fetchrow(
                """
                SELECT COUNT(*)::INT AS referral_count
                FROM referrals
                WHERE referrer_user_id = (SELECT id FROM users WHERE telegram_id = $1)
                  AND created_at >= CURRENT_TIMESTAMP - ($2::INT * INTERVAL '1 day')
                """,
                int(telegram_id), days,
            )
        count = int(row["referral_count"] or 0) if row else 0
        return {
            "discount_percent": min(maximum, count * per_user),
            "referral_count": count,
        }
    finally:
        if own_conn:
            await conn.close()


