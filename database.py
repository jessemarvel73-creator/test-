                # releases the hold and must not create a positive balance entry.
            result=await conn.execute(
                "UPDATE orders SET status='cancelled', updated_at=CURRENT_TIMESTAMP WHERE id=$1 AND status='pending'", int(order_id)
            )
            return result.endswith('1')


