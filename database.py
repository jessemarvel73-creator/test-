async def create_pending_order(telegram_id, product_id, quantity=1):
    if int(quantity) <= 0:
        raise ValueError("Invalid quantity.")

    pool = await get_pool()

    async with pool.acquire() as conn:
        async with conn.transaction():
            user = await conn.fetchrow(
                "SELECT id FROM users WHERE telegram_id = $1",
                telegram_id,
            )

            if not user:
                raise ValueError("User not found.")

            product = await conn.fetchrow(
                """
                SELECT id, name, description, price_stars, discount_percent, stock, active
                FROM products
                WHERE id = $1
                FOR UPDATE
                """,
                product_id,
            )

            if not product:
                raise ValueError("Product not found.")

            if not product["active"]:
                raise ValueError("Product is inactive.")

            await _require_available_inventory(conn, product_id, int(quantity))

            if int(product["stock"] or 0) < int(quantity):
                raise ValueError("Not enough stock.")

            base_price = int(product["price_stars"] or 0)
            discount_percent = max(0, min(100, int(product["discount_percent"] or 0)))
            price = max(1, base_price - ((base_price * discount_percent) // 100))

            if base_price <= 0:
                raise ValueError("Invalid product price.")

            total = price * int(quantity)

            order = await conn.fetchrow(
                """
                INSERT INTO orders (user_id, status, total_stars)
                VALUES ($1, 'pending', $2)
                RETURNING id
                """,
                user["id"],
                total,
            )

            await conn.execute(
                """
                INSERT INTO order_items (
                    order_id, product_id, quantity, price_stars
                )
                VALUES ($1, $2, $3, $4)
                """,
                order["id"],
                product["id"],
                int(quantity),
                price,
            )

            return {
                "order_id": order["id"],
                "product_id": product["id"],
                "name": product["name"],
                "description": product["description"],
                "price_stars": price,
                "original_price_stars": base_price,
                "discount_percent": discount_percent,
                "quantity": int(quantity),
                "total_stars": total,
            }


async def create_admin_test_order(product_id, quantity=1, complete=False):
    """Create a store order for the configured admin account for testing.

    When complete=True, the order is marked paid and inventory is delivered to
    the admin account without charging Telegram Stars.
    """
    import uuid
    import json
    import config

    quantity = int(quantity)
    product_id = int(product_id)
    if quantity <= 0:
        raise ValueError("Quantity must be greater than zero.")

    admin = await get_or_create_user(
        telegram_id=int(config.ADMIN_ID),
        username=getattr(config, "ADMIN_USERNAME", "") or None,
        first_name="Admin",
        last_name=None,
        language_code="en",
    )

    pool = await get_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            product = await conn.fetchrow(
                """SELECT id,name,price_stars,discount_percent,stock,active
                   FROM products WHERE id=$1 FOR UPDATE""",
                product_id,
            )
            if not product:
                raise ValueError("Product not found.")
            if not product["active"]:
                raise ValueError("Product is inactive.")
            await _require_available_inventory(conn, product_id, quantity)
            if int(product["stock"] or 0) < quantity:
                raise ValueError("Not enough stock.")

            base = int(product["price_stars"] or 0)
            discount = max(0, min(100, int(product["discount_percent"] or 0)))
            unit = max(1, base - ((base * discount) // 100))
            total = unit * quantity

            order = await conn.fetchrow(
                """INSERT INTO orders(user_id,status,total_stars)
                   VALUES($1,'pending',$2) RETURNING id,status,total_stars,created_at""",
                admin["id"], total,
            )
            await conn.execute(
                """INSERT INTO order_items(order_id,product_id,quantity,price_stars)
                   VALUES($1,$2,$3,$4)""",
                order["id"], product["id"], quantity, unit,
            )

            delivered = []
            if complete:
                items = await conn.fetch(
                    """SELECT id,item_data FROM inventory_items
                       WHERE product_id=$1 AND status='available'
                       ORDER BY id ASC FOR UPDATE LIMIT $2""",
                    product_id, quantity,
                )
                if len(items) < quantity:
                    raise ValueError("Inventory for this product is incomplete.")
                for item in items:
                    if item["item_data"] is not None:
                        delivered.append(str(item["item_data"]))
                    await conn.execute(
                        "UPDATE inventory_items SET status='sold', sold_at=CURRENT_TIMESTAMP WHERE id=$1",
                        item["id"],
                    )

                await conn.execute(
                    "UPDATE products SET stock=stock-$1, updated_at=CURRENT_TIMESTAMP WHERE id=$2",
                    quantity, product_id,
                )
                charge = f"ADMIN-TEST-{order['id']}-{uuid.uuid4().hex}"
                await conn.execute(
                    """INSERT INTO payments
                       (order_id,user_id,amount_stars,telegram_payment_charge_id,status)
                       VALUES($1,$2,$3,$4,'paid')""",
                    order["id"], admin["id"], total, charge,
                )
                await conn.execute(
                    "UPDATE orders SET status='paid', updated_at=CURRENT_TIMESTAMP WHERE id=$1",
                    order["id"],
                )
                await conn.execute(
                    """INSERT INTO order_deliveries(order_id,user_id,items_json,status,delivered_at)
                       VALUES($1,$2,$3,'delivered',CURRENT_TIMESTAMP)
                       ON CONFLICT(order_id) DO UPDATE SET items_json=EXCLUDED.items_json,
                           status='delivered', delivered_at=CURRENT_TIMESTAMP""",
                    order["id"], admin["id"], json.dumps(delivered, ensure_ascii=False),
                )

            return {
                "order_id": int(order["id"]),
                "status": "paid" if complete else "pending",
                "total_stars": int(total),
                "product_name": str(product["name"]),
                "quantity": quantity,
                "inventory_items": delivered,
                "telegram_id": int(config.ADMIN_ID),
            }


async def cancel_pending_order(order_id, telegram_id):
    pool = await get_pool()
