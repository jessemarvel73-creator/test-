async def expire_stale_pending_orders(ttl_minutes=30, limit=100):
    """Cancel old unpaid orders and release any loyalty reservation they hold.

    This is safe to run repeatedly and concurrently because rows are locked with
    SKIP LOCKED before they are changed from pending to cancelled.
    """
    ttl_minutes = max(5, int(ttl_minutes))
    limit = max(1, min(int(limit), 200))
    pool = await get_pool()
    cancelled = []
    async with pool.acquire() as conn:
        async with conn.transaction():
            rows = await conn.fetch(
                """SELECT o.id, o.user_id, o.total_stars, o.loyalty_redemption_id,
                          u.telegram_id
                   FROM orders o
                   JOIN users u ON u.id=o.user_id
                   WHERE o.status='pending'
                     AND o.created_at <= CURRENT_TIMESTAMP - ($1::integer * INTERVAL '1 minute')
                   ORDER BY o.created_at ASC, o.id ASC
                   FOR UPDATE SKIP LOCKED
                   LIMIT $2""",
                ttl_minutes, limit,
            )
            for row in rows:
                changed = await conn.fetchrow(
                    """UPDATE orders
                       SET status='cancelled', updated_at=CURRENT_TIMESTAMP
                       WHERE id=$1 AND status='pending'
                       RETURNING id""",
                    int(row["id"]),
                )
                if not changed:
                    continue
                if row["loyalty_redemption_id"]:
                    await conn.execute(
                        """UPDATE loyalty_redemptions
                           SET status='cancelled', order_id=NULL
                           WHERE id=$1 AND status='reserved'""",
                        int(row["loyalty_redemption_id"]),
                    )
                cancelled.append({
                    "order_id": int(row["id"]),
                    "telegram_id": int(row["telegram_id"]),
                    "total_stars": int(row["total_stars"] or 0),
                })
    return cancelled

