async def _normalize_promo_allowed_users(conn, entries):
    """Resolve a list of numeric Telegram IDs and/or @usernames.

    Numeric IDs are accepted even when the user has not started the bot yet.
    Usernames are resolved against users currently known to the shop so that
    we can store the stable Telegram ID and enforce the restriction later.
    """
    if entries is None:
        return []
    if isinstance(entries, str):
        raw_values = [x.strip() for x in entries.replace(',', '\n').splitlines() if x.strip()]
    else:
        raw_values = [str(x).strip() for x in entries if str(x).strip()]

    if len(raw_values) > 100:
        raise ValueError("A promo can be limited to a maximum of 100 customers.")

    resolved = []
    seen = set()
    for raw in raw_values:
        value = raw.strip()
        if not value:
            continue
        if value.startswith('@'):
            username = value[1:].strip()
            if not username:
                raise ValueError("Invalid username.")
            row = await conn.fetchrow(
                "SELECT telegram_id, username FROM users WHERE LOWER(COALESCE(username,''))=LOWER($1) LIMIT 1",
                username,
            )
            if not row:
                raise ValueError(f"Username @{username} was not found. The customer must start the bot first.")
            telegram_id = int(row['telegram_id'])
            stored_username = str(row.get('username') or username)
        else:
            try:
                telegram_id = int(value)
            except (TypeError, ValueError):
                raise ValueError(f"Invalid customer: {value}. Use a Telegram ID or @username.")
            if telegram_id <= 0:
                raise ValueError(f"Invalid Telegram ID: {value}.")
            row = await conn.fetchrow("SELECT username FROM users WHERE telegram_id=$1 LIMIT 1", telegram_id)
            stored_username = str(row.get('username') or '') if row else ''

        if telegram_id not in seen:
            seen.add(telegram_id)
            resolved.append((telegram_id, stored_username))

    if not resolved:
        raise ValueError("At least one customer must be specified.")
    return resolved


async def set_promo_allowed_users(promo_id, entries):
    promo_id = int(promo_id)
    pool = await get_pool()
    async with pool.acquire() as conn:
        await ensure_promo_schema(conn)
        async with conn.transaction():
            promo = await conn.fetchrow("SELECT id, access_mode FROM promo_codes WHERE id=$1 FOR UPDATE", promo_id)
            if not promo:
                raise ValueError("Promo code not found.")
            resolved = await _normalize_promo_allowed_users(conn, entries)
            await conn.execute("DELETE FROM promo_allowed_users WHERE promo_code_id=$1", promo_id)
            for telegram_id, username in resolved:
                await conn.execute(
                    "INSERT INTO promo_allowed_users(promo_code_id,telegram_id,username) VALUES($1,$2,$3) ON CONFLICT DO NOTHING",
                    promo_id, telegram_id, username,
                )
            first_id = resolved[0][0] if resolved else None
            assigned = await conn.fetchrow("SELECT id FROM users WHERE telegram_id=$1 LIMIT 1", first_id) if first_id else None
            await conn.execute(
                "UPDATE promo_codes SET assigned_user_id=$1, access_mode='assigned' WHERE id=$2",
                assigned['id'] if assigned else None, promo_id,
            )
            return await conn.fetchrow("SELECT * FROM promo_codes WHERE id=$1", promo_id)


