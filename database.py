async def create_promo_code(code, discount_percent=0, discount_stars=0, max_uses=None, expires_at=None,
                          sale_price_stars=0, target_type="global", target_id=None,
                          min_cart_quantity=1, max_uses_per_user=1, description="",
                          access_mode="public", assigned_user_id=None, allowed_customers=None):
    normalized = str(code or "").strip().upper()
    if not normalized:
        raise ValueError("Promo code is required.")
    percent = int(discount_percent or 0)
    fixed = int(discount_stars or 0)
    if percent < 0 or percent > 100:
        raise ValueError("Discount percent must be between 0 and 100.")
    if fixed < 0:
        raise ValueError("Discount Stars cannot be negative.")
    if percent > 0 and fixed > 0:
        raise ValueError("Use either percentage or fixed Stars discount, not both.")
    if percent == 0 and fixed == 0:
        raise ValueError("Set a percentage or fixed Stars discount.")
    uses = None if max_uses in (None, "", 0) else int(max_uses)
    if uses is not None and uses <= 0:
        raise ValueError("Max uses must be greater than zero.")
    sale_price = max(0, int(sale_price_stars or 0))
    mode = str(access_mode or "public").strip().lower()
    if mode not in {"sale", "assigned", "public"}:
        raise ValueError("Invalid promo access mode.")
    if mode == "sale" and sale_price <= 0:
        raise ValueError("Sale promos must have a sale price greater than zero.")
    if mode != "sale":
        sale_price = 0

    target = str(target_type or "global").strip().lower()
    if target not in {"global", "product", "game", "category"}:
        raise ValueError("Invalid promo target type.")
    target_value = None if target == "global" else int(target_id or 0)
    if target != "global" and target_value <= 0:
        raise ValueError("A valid target ID is required for this promo type.")
    min_qty = int(min_cart_quantity or 1)
    if min_qty < 1:
        raise ValueError("Minimum cart quantity must be at least 1.")
    per_user = int(max_uses_per_user or 0)
    if per_user < 0:
        raise ValueError("Max uses per user cannot be negative.")
    description = str(description or "").strip()[:2000]

    # PostgreSQL TIMESTAMP parameters must be datetime objects, not text.
    # Admin Telegram input arrives as a string, so normalize it once here.
    if expires_at not in (None, "", "-", "none", "null") and isinstance(expires_at, str):
        raw_expiry = expires_at.strip()
        try:
            expires_at = datetime.fromisoformat(raw_expiry.replace("Z", "+00:00"))
        except ValueError:
            raise ValueError("Invalid expiry timestamp. Use YYYY-MM-DD HH:MM:SS.")
        if expires_at.tzinfo is not None:
            expires_at = expires_at.replace(tzinfo=None)
    elif expires_at in ("", "-", "none", "null"):
        expires_at = None

    pool = await get_pool()
    async with pool.acquire() as conn:
        await ensure_promo_schema(conn)
        if target != "global":
            table = {"product": "products", "game": "games", "category": "categories"}[target]
            target_row = await conn.fetchrow(f"SELECT id FROM {table} WHERE id=$1", target_value)
            if not target_row:
                raise ValueError(f"Target {target} #{target_value} was not found.")

        resolved = []
        if mode == "assigned":
            if allowed_customers is not None:
                resolved = await _normalize_promo_allowed_users(conn, allowed_customers)
            elif assigned_user_id is not None:
                row = await conn.fetchrow("SELECT telegram_id, username FROM users WHERE id=$1", int(assigned_user_id))
                if not row:
                    raise ValueError("Assigned customer was not found.")
                resolved = [(int(row['telegram_id']), str(row.get('username') or ''))]
            else:
                raise ValueError("Specific Customer mode requires at least one customer.")
            if not resolved:
                raise ValueError("Specific Customer mode requires at least one customer.")
        try:
            row = await conn.fetchrow(
                """INSERT INTO promo_codes
                   (code, discount_percent, discount_stars, max_uses, active, expires_at,
                    sale_price_stars, access_mode, assigned_user_id, target_type, target_id, min_cart_quantity,
                    max_uses_per_user, description)
                   VALUES ($1,$2,$3,$4,TRUE,$5,$6,$7,$8,$9,$10,$11,$12,$13) RETURNING *""",
                normalized, percent, fixed, uses, expires_at, sale_price, mode,
                None, target, target_value, min_qty, per_user, description,
            )
            if mode == "assigned":
                for telegram_id, username in resolved:
                    await conn.execute(
                        "INSERT INTO promo_allowed_users(promo_code_id,telegram_id,username) VALUES($1,$2,$3) ON CONFLICT DO NOTHING",
                        row['id'], telegram_id, username,
                    )
                # Keep the legacy assigned_user_id populated only for a single
                # customer. For 2-100 customers, the allow-list is authoritative.
                if len(resolved) == 1:
                    first = await conn.fetchrow("SELECT id FROM users WHERE telegram_id=$1 LIMIT 1", resolved[0][0])
                    if first:
                        row = await conn.fetchrow("UPDATE promo_codes SET assigned_user_id=$1 WHERE id=$2 RETURNING *", first['id'], row['id'])
                else:
                    row = await conn.fetchrow("UPDATE promo_codes SET assigned_user_id=NULL WHERE id=$1 RETURNING *", row['id'])
        except Exception as e:
            if "promo_codes_code_key" in str(e) or "duplicate key" in str(e).lower():
                raise ValueError("A promo code with this name already exists.")
            raise
        return dict(row)


async def update_promo_code(promo_id, *args, **kwargs):
    """Update an existing promo code without changing unspecified fields.

    This function accepts either keyword arguments or a single mapping as the
    second positional argument. It is intentionally tolerant because older
    bot/admin builds used slightly different update-call shapes.
    """
    try:
        promo_id = int(promo_id)
    except (TypeError, ValueError):
        raise ValueError("Invalid promo code ID.")

    data = {}
    if args:
        if len(args) == 1 and isinstance(args[0], dict):
            data.update(args[0])
        else:
            positional_fields = [
                "code",
                "discount_percent",
                "discount_stars",
                "max_uses",
                "expires_at",
                "sale_price_stars",
                "target_type",
                "target_id",
                "min_cart_quantity",
                "max_uses_per_user",
                "description",
                "active",
                "access_mode",
                "assigned_user_id",
            ]
            if len(args) > len(positional_fields):
                raise ValueError("Too many promo code update arguments.")
            data.update(dict(zip(positional_fields, args)))
    data.update(kwargs)

    # Accept common aliases used by admin clients.
    if "fixed_discount_stars" in data and "discount_stars" not in data:
        data["discount_stars"] = data.pop("fixed_discount_stars")
    if "price_stars" in data and "sale_price_stars" not in data:
        data["sale_price_stars"] = data.pop("price_stars")
    if "sale_price" in data and "sale_price_stars" not in data:
        data["sale_price_stars"] = data.pop("sale_price")
    if "target" in data and "target_type" not in data:
        data["target_type"] = data.pop("target")
    if "target_value" in data and "target_id" not in data:
        data["target_id"] = data.pop("target_value")
    if "max_uses_user" in data and "max_uses_per_user" not in data:
        data["max_uses_per_user"] = data.pop("max_uses_user")

    allowed = {
        "code",
        "discount_percent",
        "discount_stars",
        "max_uses",
        "expires_at",
        "sale_price_stars",
        "target_type",
        "target_id",
        "min_cart_quantity",
        "max_uses_per_user",
        "description",
        "active",
        "access_mode",
        "assigned_user_id",
    }
    changes = {k: v for k, v in data.items() if k in allowed}
    if not changes:
        row = await fetch_one("SELECT * FROM promo_codes WHERE id = ?", (promo_id,))
        if not row:
            raise ValueError("Promo code not found.")
        return row

    current = await fetch_one("SELECT * FROM promo_codes WHERE id = ?", (promo_id,))
    if not current:
        raise ValueError("Promo code not found.")

    # Merge values for validation while only writing fields explicitly supplied.
    merged = dict(current)
    merged.update(changes)

    normalized = str(merged.get("code") or "").strip().upper()
    if not normalized:
        raise ValueError("Promo code is required.")

    percent = int(merged.get("discount_percent") or 0)
    fixed = int(merged.get("discount_stars") or 0)
    if percent < 0 or percent > 100:
        raise ValueError("Discount percent must be between 0 and 100.")
    if fixed < 0:
        raise ValueError("Discount Stars cannot be negative.")
    if percent > 0 and fixed > 0:
        raise ValueError("Use either percentage or fixed Stars discount, not both.")
    if percent == 0 and fixed == 0:
        raise ValueError("Set a percentage or fixed Stars discount.")

    uses = merged.get("max_uses")
    if uses in (None, "", 0):
        uses = None
    else:
        uses = int(uses)
        if uses <= 0:
            raise ValueError("Max uses must be greater than zero.")

    sale_price = max(0, int(merged.get("sale_price_stars") or 0))
    target = str(merged.get("target_type") or "global").strip().lower()
    if target not in {"global", "product", "game", "category"}:
        raise ValueError("Invalid promo target type.")

    target_value = merged.get("target_id")
    if target == "global":
        target_value = None
    else:
        if target_value in (None, "", 0):
            raise ValueError("A valid target ID is required for this promo type.")
        target_value = int(target_value)

    min_qty = int(merged.get("min_cart_quantity") or 1)
    if min_qty < 1:
        raise ValueError("Minimum cart quantity must be at least 1.")

    per_user = int(merged.get("max_uses_per_user") or 0)
    if per_user < 0:
        raise ValueError("Max uses per user cannot be negative.")

    description = str(merged.get("description") or "").strip()[:2000]
    active = bool(merged.get("active"))
    expires_at = merged.get("expires_at")
    # asyncpg requires datetime/date for PostgreSQL TIMESTAMP parameters.
    if expires_at not in (None, "", "-", "none", "null") and isinstance(expires_at, str):
        raw_expiry = expires_at.strip()
        try:
            expires_at = datetime.fromisoformat(raw_expiry.replace("Z", "+00:00"))
        except ValueError:
            raise ValueError("Invalid expiry timestamp. Use YYYY-MM-DD HH:MM:SS.")
        if expires_at.tzinfo is not None:
            expires_at = expires_at.replace(tzinfo=None)
    elif expires_at in ("", "-", "none", "null"):
        expires_at = None
    mode = str(merged.get("access_mode") or ("assigned" if merged.get("assigned_user_id") else ("sale" if sale_price > 0 else "public"))).strip().lower()
    if mode not in {"sale", "assigned", "public"}:
        raise ValueError("Invalid promo access mode.")
    if mode == "sale" and sale_price <= 0:
        raise ValueError("Sale promos must have a sale price greater than zero.")
    if mode != "sale":
        sale_price = 0

    pool = await get_pool()
    async with pool.acquire() as conn:
        await ensure_promo_schema(conn)
        if target != "global":
            table = {"product": "products", "game": "games", "category": "categories"}[target]
            target_row = await conn.fetchrow(
                f"SELECT id FROM {table} WHERE id=$1",
                target_value,
            )
            if not target_row:
                raise ValueError(f"Target {target} #{target_value} was not found.")

        try:
            row = await conn.fetchrow(
                """UPDATE promo_codes
                   SET code=$1,
                       discount_percent=$2,
                       discount_stars=$3,
                       max_uses=$4,
                       expires_at=$5,
                       sale_price_stars=$6,
                       target_type=$7,
                       target_id=$8,
                       min_cart_quantity=$9,
                       max_uses_per_user=$10,
                       description=$11,
                       active=$12,
                       access_mode=$13,
                       assigned_user_id=$14
                   WHERE id=$15
                   RETURNING *""",
                normalized,
                percent,
                fixed,
                uses,
                expires_at,
                sale_price,
                target,
                target_value,
                min_qty,
                per_user,
                description,
                active,
                mode,
                int(merged.get("assigned_user_id")) if merged.get("assigned_user_id") not in (None, "") else None,
                promo_id,
            )
        except Exception as e:
            if "promo_codes_code_key" in str(e) or "duplicate key" in str(e).lower():
                raise ValueError("A promo code with this name already exists.")
            raise

        if not row:
            raise ValueError("Promo code not found.")
        return dict(row)


