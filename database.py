def _convert_query(query, params):
    if not params:
        return query

    result = []
    index = 0

    for char in query:
        if char == "?":
            index += 1
            result.append(f"${index}")
        else:
            result.append(char)

    return "".join(result)


async def get_pool():
    global _pool

    if _pool is None:
        if not DATABASE_URL:
            raise RuntimeError("DATABASE_URL is missing.")

        _pool = await asyncpg.create_pool(
            DATABASE_URL,
            min_size=1,
            max_size=5,
            command_timeout=30,
        )

    return _pool


async def ensure_promo_schema(conn):
    """Ensure the current Promo Shop schema exists on older Render databases."""
    global _PROMO_SCHEMA_READY
    if _PROMO_SCHEMA_READY:
        return
    await conn.execute("""
        CREATE TABLE IF NOT EXISTS promo_codes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code TEXT UNIQUE NOT NULL,
            discount_percent INTEGER DEFAULT 0,
            discount_stars INTEGER DEFAULT 0,
            max_uses INTEGER,
            used_count INTEGER DEFAULT 0,
            active BOOLEAN DEFAULT TRUE,
            expires_at TIMESTAMP,
            sale_price_stars INTEGER NOT NULL DEFAULT 0,
            access_mode TEXT NOT NULL DEFAULT 'public',
            assigned_user_id BIGINT,
            sold_to_user_id BIGINT,
            sold_at TIMESTAMP,
            telegram_payment_charge_id TEXT,
            target_type TEXT NOT NULL DEFAULT 'global',
            target_id BIGINT,
            min_cart_quantity INTEGER NOT NULL DEFAULT 1,
            max_uses_per_user INTEGER NOT NULL DEFAULT 1,
            description TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    for sql in (
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS sale_price_stars INTEGER NOT NULL DEFAULT 0",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS access_mode TEXT NOT NULL DEFAULT 'public'",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS assigned_user_id BIGINT",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS sold_to_user_id BIGINT",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS sold_at TIMESTAMP",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS telegram_payment_charge_id TEXT",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS target_type TEXT NOT NULL DEFAULT 'global'",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS target_id BIGINT",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS min_cart_quantity INTEGER NOT NULL DEFAULT 1",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS max_uses_per_user INTEGER NOT NULL DEFAULT 1",
        "ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS description TEXT DEFAULT ''",
    ):
        await conn.execute(sql)
    await conn.execute("""
        CREATE TABLE IF NOT EXISTS promo_allowed_users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            promo_code_id BIGINT NOT NULL REFERENCES promo_codes(id) ON DELETE CASCADE,
            telegram_id BIGINT NOT NULL,
            username TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(promo_code_id, telegram_id)
        )
    """)
    await conn.execute("""
        CREATE TABLE IF NOT EXISTS promo_redemptions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            promo_code_id BIGINT NOT NULL REFERENCES promo_codes(id) ON DELETE CASCADE,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    await conn.execute("ALTER TABLE promo_redemptions ADD COLUMN IF NOT EXISTS quantity INTEGER NOT NULL DEFAULT 1")
    await conn.execute("UPDATE promo_redemptions SET quantity=1 WHERE quantity IS NULL OR quantity < 1")
    await conn.execute("ALTER TABLE promo_redemptions DROP CONSTRAINT IF EXISTS promo_redemptions_promo_code_id_user_id_key")
    await conn.execute("CREATE INDEX IF NOT EXISTS idx_promo_allowed_users_promo ON promo_allowed_users(promo_code_id, telegram_id)")
    await conn.execute("CREATE INDEX IF NOT EXISTS idx_promo_redemptions_user_code ON promo_redemptions(user_id, promo_code_id, created_at DESC)")
    await conn.execute("CREATE INDEX IF NOT EXISTS idx_promo_codes_active_target ON promo_codes(active, target_type, target_id)")
    await conn.execute("UPDATE promo_codes SET access_mode='assigned' WHERE access_mode='public' AND assigned_user_id IS NOT NULL")
    await conn.execute("UPDATE promo_codes SET access_mode='sale' WHERE access_mode='public' AND assigned_user_id IS NULL AND sale_price_stars > 0")
    await conn.execute("""
        INSERT INTO promo_allowed_users(promo_code_id, telegram_id, username)
        SELECT p.id, u.telegram_id, COALESCE(u.username,'')
          FROM promo_codes p
          JOIN users u ON u.id=p.assigned_user_id
         WHERE p.assigned_user_id IS NOT NULL
           AND p.access_mode='assigned'
        ON CONFLICT (promo_code_id, telegram_id) DO NOTHING
    """)
    _PROMO_SCHEMA_READY = True


