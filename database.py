        user = await conn.fetchrow("SELECT id FROM users WHERE telegram_id=$1", int(telegram_id))
        if not user:
            return {"balance":0,"earned":0,"spent":0,"reserved":0,"available":0,"level":"Bronze","next_level_points":500,"level_progress":0}
        await release_expired_loyalty_redemptions(conn, user["id"])
        row = await conn.fetchrow(
            """SELECT
                COALESCE(SUM(amount),0)::INT AS balance,
                COALESCE(SUM(CASE WHEN amount>0 THEN amount ELSE 0 END),0)::INT AS earned,
                COALESCE(SUM(CASE WHEN amount<0 THEN -amount ELSE 0 END),0)::INT AS spent
               FROM loyalty_transactions WHERE user_id=$1""", user["id"]
        )
        reserved = await conn.fetchval(
            """SELECT COALESCE(SUM(points_spent),0) FROM loyalty_redemptions
               WHERE user_id=$1 AND status='reserved' AND expires_at > CURRENT_TIMESTAMP""", user["id"]
        )
        balance=int(row["balance"] or 0); earned=int(row["earned"] or 0); spent=int(row["spent"] or 0); reserved=int(reserved or 0)
        available=max(0,balance-reserved)
        if earned >= 2000:
            level='Gold'; next_points=0; progress=100
        elif earned >= 500:
            level='Silver'; next_points=2000; progress=int(((earned-500)/1500)*100)
        else:
            level='Bronze'; next_points=500; progress=int((earned/500)*100)
        return {"balance":balance,"earned":earned,"spent":spent,"reserved":reserved,"available":available,"level":level,"next_level_points":next_points,"level_progress":max(0,min(100,progress))}


