async def create_pending_order_from_cart(telegram_id, promo_code=None, loyalty_redemption_id=None):
    pool = await get_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            user = await conn.fetchrow("SELECT id FROM users WHERE telegram_id = $1", telegram_id)
            if not user:
                raise ValueError("User not found.")
            await release_expired_loyalty_redemptions(conn, user["id"])
            cart = await conn.fetchrow(
                "SELECT id FROM carts WHERE user_id = $1 AND status = 'active' ORDER BY id DESC LIMIT 1",
                user["id"],
            )
            if not cart:
                raise ValueError("Your cart is empty.")
            items = await conn.fetch(
                """SELECT ci.product_id, ci.quantity, p.name, p.description, p.price_stars,
                          p.discount_percent, p.stock, p.active, p.game_id, p.category_id
                   FROM cart_items ci JOIN products p ON p.id = ci.product_id
                   WHERE ci.cart_id = $1 ORDER BY ci.id ASC FOR UPDATE OF p""",
                cart["id"],
            )
            if not items:
                raise ValueError("Your cart is empty.")
            subtotal = 0
            for item in items:
                if not item["active"]:
                    raise ValueError(f"Product is unavailable: {item['name']}")
                if int(item["quantity"]) <= 0:
                    raise ValueError("Invalid cart quantity.")
                if int(item["stock"] or 0) < int(item["quantity"]):
                    raise ValueError(f"Not enough stock for {item['name']}.")
                available = await conn.fetchval(
                    "SELECT COUNT(*) FROM inventory_items WHERE product_id=$1 AND status='available'",
                    int(item["product_id"]),
                )
                if int(available or 0) < int(item["quantity"]):
                    raise ValueError(f"Inventory is not available for {item['name']}. Add inventory first.")
                base_price = int(item["price_stars"] or 0)
                if base_price <= 0:
                    raise ValueError(f"Invalid price for {item['name']}.")
                product_discount = max(0, min(100, int(item["discount_percent"] or 0)))
                sale_price = max(1, base_price - ((base_price * product_discount) // 100))
                subtotal += sale_price * int(item["quantity"])

            promo = None
            total = subtotal
            discount_stars = 0
            if str(promo_code or "").strip():
                promo = await calculate_promo_discount(
                    telegram_id=telegram_id, code=promo_code, subtotal_stars=subtotal, conn=conn
                )
                if not promo.get("valid"):
                    raise ValueError(promo.get("error") or "Invalid promo code.")
                discount_stars = int(promo["discount_stars"])
                total = int(promo["total_stars"])

            referral_info = await get_referral_discount(telegram_id, conn=conn)
            referral_discount_percent = int(referral_info.get("discount_percent") or 0)
            referral_discount_stars = 0
            if referral_discount_percent > 0:
                referral_discount_stars = min(
                    int(total),
                    (int(total) * referral_discount_percent) // 100,
                )
                total = max(0, int(total) - referral_discount_stars)

            loyalty = None
            loyalty_discount = 0
            if loyalty_redemption_id:
                loyalty = await conn.fetchrow(
                    """SELECT id, points_spent, discount_stars, status, expires_at
                       FROM loyalty_redemptions
                       WHERE id=$1 AND user_id=$2 FOR UPDATE""",
                    int(loyalty_redemption_id), user["id"],
                )
                if not loyalty:
                    raise ValueError("Reward redemption not found.")
                if loyalty["status"] != "reserved":
                    raise ValueError("This reward has already been used or cancelled.")
                if loyalty["expires_at"] is not None and loyalty["expires_at"] <= __import__("datetime").datetime.utcnow():
                    await conn.execute("UPDATE loyalty_redemptions SET status='cancelled' WHERE id=$1", loyalty["id"])
                    raise ValueError("This reward has expired. Redeem it again.")
                loyalty_discount = min(int(loyalty["discount_stars"]), max(0, total))
                total = max(0, total - loyalty_discount)

            order = await conn.fetchrow(
                """INSERT INTO orders
                   (user_id, status, total_stars, promo_quantity, promo_code_id, promo_discount_stars, loyalty_redemption_id, loyalty_discount_stars, referral_discount_stars)
                   VALUES ($1,'pending',$2,$3,$4,$5,$6,$7,$8) RETURNING id""",
                user["id"], total,
                int(promo.get("promo_quantity") or 0) if promo else 0,
                promo["promo_code_id"] if promo else None,
                discount_stars,
                loyalty["id"] if loyalty else None,
                loyalty_discount,
                referral_discount_stars,
            )
            for item in items:
                product_discount = max(0, min(100, int(item["discount_percent"] or 0)))
                base_price = int(item["price_stars"] or 0)
                sale_price = max(1, base_price - ((base_price * product_discount) // 100))
                await conn.execute(
                    "INSERT INTO order_items (order_id, product_id, quantity, price_stars) VALUES ($1, $2, $3, $4)",
                    order["id"], item["product_id"], int(item["quantity"]), sale_price,
                )

            if loyalty:
                await conn.execute(
                    "UPDATE loyalty_redemptions SET order_id=$2 WHERE id=$1 AND status='reserved'",
                    loyalty["id"], order["id"],
                )

            return {
                "order_id": int(order["id"]),
                "subtotal_stars": subtotal,
                "discount_stars": discount_stars + referral_discount_stars + loyalty_discount,
                "promo_discount_stars": discount_stars,
                "promo_quantity": int(promo.get("promo_quantity") or 0) if promo else 0,
                "loyalty_discount_stars": loyalty_discount,
                "referral_discount_stars": referral_discount_stars,
                "referral_discount_percent": referral_discount_percent,
                "total_stars": total,
                "promo_code": promo["code"] if promo else None,
                "loyalty_redemption_id": int(loyalty["id"]) if loyalty else None,
                "items": [dict(x) for x in items],
            }


