        await ensure_promo_schema(conn)
        async with conn.transaction():
            user = await conn.fetchrow("SELECT id FROM users WHERE telegram_id=$1", int(telegram_id))
            if not user:
                raise ValueError("User not found.")
            promo = await conn.fetchrow("SELECT * FROM promo_codes WHERE id=$1 FOR UPDATE", int(promo_id))
            if not promo or not promo["active"]:
                return None
            existing_owner = promo.get("sold_to_user_id")
            existing_charge = str(promo.get("telegram_payment_charge_id") or "")
            if existing_owner is not None:
                if existing_charge and existing_charge == str(charge_id) and int(existing_owner) == int(user["id"]):
                    return dict(promo)
                return None
            if str(promo.get("access_mode") or "public").strip().lower() != "sale":
                return None
            if int(promo.get("sale_price_stars") or 0) <= 0:
                return None
            if promo.get("max_uses") is not None:
                total_used, _ = await get_promo_usage_counts(conn, promo_id)
                if total_used >= int(promo["max_uses"]):
                    return None
            if promo.get("expires_at") is not None and promo["expires_at"] <= __import__("datetime").datetime.utcnow():
                return None
            mode = str(promo.get("access_mode") or "public").strip().lower()
            if mode == "assigned":
                allowed = await conn.fetchval(
                    "SELECT 1 FROM promo_allowed_users WHERE promo_code_id=$1 AND telegram_id=$2 LIMIT 1",
                    int(promo_id), int(telegram_id),
                )
                legacy_match = promo["assigned_user_id"] is not None and int(promo["assigned_user_id"]) == int(user["id"])
                if not allowed and not legacy_match:
                    return None
            row = await conn.fetchrow(
                """UPDATE promo_codes
                   SET sold_to_user_id=$1, sold_at=CURRENT_TIMESTAMP, telegram_payment_charge_id=$2
                 WHERE id=$3 AND active=TRUE AND sold_to_user_id IS NULL
                 RETURNING *""",
                user["id"], str(charge_id), int(promo_id),
            )
            return dict(row) if row else None


